export type PixelValue = 0 | 1 | 2;

export type Sprite = {
  id: string;
  name: string;
  width: number;
  height: number;
  pixels: PixelValue[];
};

function rowsToPixels(rows: string[]): PixelValue[] {
  return rows.flatMap((row) =>
    row.split("").map((pixel): PixelValue => {
      if (pixel === "1") {
        return 1;
      }

      if (pixel === "2") {
        return 2;
      }

      return 0;
    }),
  );
}

